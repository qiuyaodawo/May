import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import * as rootApi from "@may/application";
import { GitCheckpointError, GitWorkspaceConflictError, ProjectGitWorkspace } from "@may/application/git-workspace";

const directory = dirname(fileURLToPath(import.meta.url));
assert.ok((await realpath(fileURLToPath(import.meta.resolve("@may/application/git-workspace")))).startsWith(join(directory, "node_modules")));
assert.equal("ProjectGitWorkspace" in rootApi, false);
assert.equal(typeof GitCheckpointError, "function");
assert.equal(typeof GitWorkspaceConflictError, "function");
const workspace = join(directory, "project");
await mkdir(workspace);
const execute = promisify(execFile);
const git = async (...args) => (await execute("git", args, { cwd: workspace, windowsHide: true })).stdout.trim();
await git("init");
assert.equal(await git("rev-parse", "--show-toplevel"), workspace.replaceAll("\\", "/"));
await git("config", "--local", "user.name", "May packaged integration test");
await git("config", "--local", "user.email", "may-package-test@example.invalid");
await git("config", "--local", "core.autocrlf", "false");
const files = await ProjectGitWorkspace.open({ workspace, dataRoot: join(directory, "records"),
  worktreesRoot: join(directory, "worktrees"), authorizeCommit: request => request.workspace === resolve(workspace) });
await writeFile(join(workspace, "source.txt"), "initial\n");
const initial = await files.prepare("session");
assert.equal(initial.status, "committed");
const round = await files.beginRound({ sessionId: "session" });
await writeFile(join(workspace, "source.txt"), "completed\n");
const completed = await round.complete({ outcome: "completed", runId: "run", historyPosition: 5 });
assert.equal(completed.status, "committed");
assert.match((await files.diff({ from: initial.commit, to: completed.commit })).patch, /completed/u);
const preview = await files.previewRestore({ checkpointId: initial.id, paths: ["source.txt"] });
assert.equal((await files.restore(preview, { sessionId: "session", runId: "restore" })).status, "committed");
assert.equal(await readFile(join(workspace, "source.txt"), "utf8"), "initial\n");
const worktree = await files.createWorktree({ sessionId: "session", historyPosition: 1, checkpointId: initial.id });
assert.equal(await readFile(join(worktree.workspace, "source.txt"), "utf8"), "initial\n");
await files.deleteWorktree(worktree.id);
assert.equal(await git("rev-list", "--count", "HEAD"), "3");
process.stdout.write("Packed Git workspace verification passed\n");
